export function getProductById(id) {
  return products.find((p) => p.id === id);
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return [];
  const dept = product.category?.[0];
  return products
    .filter((p) => p.id !== product.id && p.category?.[0] === dept)
    .slice(0, limit);
}

export function getProductsByCategory(categoryName) {
  return products.filter((p) => p.category?.[0] === categoryName);
}

